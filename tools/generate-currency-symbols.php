<?php

use ReeStyleIt\NumberClass\Enums\Locales;

require dirname(__DIR__) . '/vendor/autoload.php';

if (! class_exists(NumberFormatter::class)) {
    fwrite(STDERR, "The intl extension is required to regenerate the symbol data.\n");
    exit(1);
}

$lines = ["<?php", '', '// Generated by composer generate:symbols.', '', 'return ['];

foreach (Locales::cases() as $locale) {
    $formatter = new NumberFormatter($locale->value, NumberFormatter::CURRENCY);
    $currency = $formatter->getTextAttribute(NumberFormatter::CURRENCY_CODE);
    $symbol = $formatter->getSymbol(NumberFormatter::CURRENCY_SYMBOL);
    $pattern = $formatter->getPattern();

    if ($currency === false || $symbol === false || $pattern === false) {
        throw new RuntimeException('Could not generate currency data for ' . $locale->value);
    }

    $positivePattern = explode(';', $pattern)[0];
    $symbolOffset = strpos($positivePattern, '¤');
    $numberOffset = strcspn($positivePattern, '#0');

    if ($symbolOffset === false) {
        throw new RuntimeException('Currency pattern has no symbol for ' . $locale->value);
    }

    $position = $symbolOffset < $numberOffset ? 'prefix' : 'suffix';
    $lines[] = '    ' . var_export($locale->value, true) . ' => [';
    $lines[] = "        'currency' => " . var_export($currency, true) . ',';
    $lines[] = "        'symbol'   => " . var_export($symbol, true) . ',';
    $lines[] = "        'position' => " . var_export($position, true) . ',';
    $lines[] = '    ],';
}

$lines[] = '];';
$directory = dirname(__DIR__) . '/src/Resources';

if (! is_dir($directory)) {
    mkdir($directory, 0777, true);
}

file_put_contents($directory . '/currency-symbols.php', implode("\n", $lines) . "\n");

echo "Locale currency symbols and positions generated.\n";
