<?php

use ReeStyleIt\NumberClass\Enums\Currencies;
use ReeStyleIt\NumberClass\Enums\Locales;

require dirname(__DIR__) . '/vendor/autoload.php';

if (!class_exists(NumberFormatter::class)) {
    fwrite(STDERR, "The intl extension is required to regenerate the symbol data.\n");
    exit(1);
}

$symbolsFor = static function (string $locale): array {
    $symbols = [];

    foreach (Currencies::cases() as $currency) {
        $symbols[$currency->value] = $currency->symbol($locale);
    }

    return $symbols;
};

$defaults = $symbolsFor('en_US');
$locales = array_map(static fn (Locales $locale): string => $locale->value, Locales::cases());
$languages = array_map(static fn (string $locale): string => explode('_', $locale)[0], $locales);
$data = ['default' => $defaults, 'locales' => ['en_us' => []], 'aliases' => []];

foreach (array_unique([...$locales, ...$languages]) as $locale) {
    $overrides = array_diff_assoc($symbolsFor($locale), $defaults);
    $name = strtolower($locale);
    $existing = array_search($overrides, $data['locales'], true);

    if ($existing !== false) {
        if ($name !== $existing) {
            $data['aliases'][$name] = $existing;
        }
    } else {
        $data['locales'][$name] = $overrides;
    }
}

$directory = dirname(__DIR__) . '/src/Resources';

if (!is_dir($directory)) {
    mkdir($directory, 0777, true);
}

file_put_contents(
    $directory . '/currency-symbols.php',
    "<?php\n\n// Generated by composer generate:symbols.\n\nreturn " . var_export($data, true) . ";\n",
);

echo "Currency symbol fallback data generated.\n";
